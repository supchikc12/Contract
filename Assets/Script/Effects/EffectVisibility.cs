// Когда эффект становится известен игроку.
public enum EffectVisibility
{
    InspectTarget,  // только после осмотра цели: кровотечение, перелом
    VisibleOnApply, // сразу: адреналин, обезболивающее
    Symptom,        // после явного симптома: осечка оружия, удар током
    KnownFromItem   // известен, пока предмет надет/изучен
}
